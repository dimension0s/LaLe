"""
indirect_prompt.py - 意译提示词

意译：融入目标语言的文化背景
"""

# ============================================================
# 系统提示词
# ============================================================
INDIRECT_SYSTEM_PROMPT = "你是一位资深翻译，擅长意译，能够融入目标语言的文化背景。"


# ============================================================
# 用户提示词模板
# ============================================================
INDIRECT_PROMPT_TEMPLATE = """请将以下文本从{source_lang}意译为{target_lang}。

【翻译要求】
1. 准确传达原文意思（这是前提）
2. 融入目标语言的文化背景
3. 语言流畅自然，符合目标语言的表达习惯
4. 可以使用目标语言中的俗语、惯用语
5. 避免直译带来的"翻译腔"

【意译说明】
- 意译不是"自由发挥"，而是"文化对等"
- 示例：英文 "black sheep" 译为中文"害群之马"
- 意译的前提是"准确"

【可用工具】
- rag: 查询翻译知识库（文化背景、翻译方法、术语等）
- web: 联网搜索（时效性信息、新词、新事件、最新译法）

【工具选择建议】
- 涉及 2024 年之后的事件、新词、最新译法 → 用 web
- 涉及人名、地名、术语、翻译方法 → 用 rag
- 都不需要 → 直接输出

【工作流程】
1. 分析原文，判断是否需要工具
2. 如果需要，输出工具调用请求
3. 如果不需要，直接输出翻译
4. 收到工具结果后，直接输出最终翻译

【输出格式】
如果需要工具，输出 JSON：
{{
    "thought": "你的思考",
    "action": "tool",
    "tools": [
        {{"type": "rag", "query": "查询内容"}}
    ]
}}

如果不需要工具，输出 JSON：
{{
    "thought": "你的思考",
    "action": "output",
    "translation_traces": "翻译结果"
}}

【原文】
{text}

【请输出 JSON】"""