# ============================================================
DIRECT_PROMPT_TEMPLATE = """请将以下文本从{source_lang}直译为{target_lang}。

【翻译要求】
1. 忠于原文，不添加、不遗漏
2. 尽量保持原文的句法结构
3. 专有名词（人名、地名、机构名）必须准确
4. 时效性信息（如近期事件）必须确认
5. 不融入目标语言的文化改写


【可用工具】
- rag: 查询翻译知识库（人名、地名、术语、翻译方法）
- web: 联网搜索（时效性信息、新词、新事件、最新译法）

【工具选择建议】
- 涉及 2024 年之后的事件、新词、最新译法 → 用 web
- 涉及人名、地名、术语、翻译方法 → 用 rag
- 都不需要 → 直接输出

【工作流程】
1. 分析原文，判断是否需要工具
2. 如果需要，输出工具调用请求
3. 如果不需要，直接输出翻译
4. 收到工具结果后，直接输出最终翻译

【输出格式】
如果需要工具，输出 JSON：
{{
    "thought": "你的思考",
    "action": "tool",
    "tools": [
        {{"type": "rag", "query": "查询内容"}}
    ]
}}

如果不需要工具，输出 JSON：
{{
    "thought": "你的思考",
    "action": "output",
    "translation_traces": "翻译结果"
}}

【原文】
{text}

【请输出 JSON】"""

